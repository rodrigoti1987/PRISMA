/* ------------------------------------------------------------
   5) MV_INTEGRACAO_SISTEMA
   Um semáforo por sistema, derivado da taxa de erro e latência
   das últimas 2 horas.
   ------------------------------------------------------------ */
CREATE MATERIALIZED VIEW MV_INTEGRACAO_SISTEMA
BUILD IMMEDIATE
REFRESH COMPLETE ON DEMAND
AS
WITH base AS (
  SELECT SISTEMA_ORIGEM, STATUS, LATENCIA_MS
  FROM EVENTO_INTEGRACAO
  WHERE HORARIO >= SYSTIMESTAMP - INTERVAL '2' HOUR
),
agregado AS (
  SELECT SISTEMA_ORIGEM,
         COUNT(*) AS QTD,
         SUM(CASE WHEN STATUS = 'ERRO' THEN 1 ELSE 0 END) AS ERROS,
         ROUND(AVG(LATENCIA_MS)) AS LAT_MEDIA
  FROM base
  GROUP BY SISTEMA_ORIGEM
)
SELECT 1 AS ORDEM, 'MV Soul' AS NOME,
       CASE WHEN NVL(a.ERROS,0) > 10 THEN 'CRITICO'
            WHEN NVL(a.ERROS,0) > 3  THEN 'DEGRADADO'
            ELSE 'OPERACIONAL' END AS STATUS,
       'Sessões ativas · resposta ' || TO_CHAR(NVL(a.LAT_MEDIA,0)) || ' ms · '
         || TO_CHAR(NVL(a.ERROS,0)) || ' erros em 2h' AS DESCRICAO,
       'resposta ' || TO_CHAR(NVL(a.LAT_MEDIA,0)) || ' ms' AS METRICA_1,
       TO_CHAR(NVL(a.ERROS,0)) || ' erros/2h'        AS METRICA_2,
       TO_CHAR(NVL(a.QTD,0)) || ' mensagens'         AS METRICA_3
FROM agregado a WHERE a.SISTEMA_ORIGEM = 'MV Soul'
UNION ALL
SELECT 2, 'PACS/RIS',
       CASE WHEN NVL(a.ERROS,0) > 10 THEN 'CRITICO'
            WHEN NVL(a.ERROS,0) > 3  THEN 'DEGRADADO'
            ELSE 'OPERACIONAL' END,
       'Estudos e laudos · ' || TO_CHAR(NVL(a.ERROS,0)) || ' falhas em 2h',
       'resposta ' || TO_CHAR(NVL(a.LAT_MEDIA,0)) || ' ms',
       TO_CHAR(NVL(a.ERROS,0)) || ' falhas/2h',
       TO_CHAR(NVL(a.QTD,0)) || ' mensagens'
FROM agregado a WHERE a.SISTEMA_ORIGEM = 'PACS/RIS'
UNION ALL
SELECT 3, 'Oracle',
       CASE WHEN NVL(a.ERROS,0) > 10 THEN 'CRITICO'
            WHEN NVL(a.ERROS,0) > 3  THEN 'DEGRADADO'
            ELSE 'OPERACIONAL' END,
       'Consultas e sessões · query média ' || TO_CHAR(NVL(a.LAT_MEDIA,0)) || ' ms',
       'query ' || TO_CHAR(NVL(a.LAT_MEDIA,0)) || ' ms',
       TO_CHAR(NVL(a.ERROS,0)) || ' erros/2h',
       TO_CHAR(NVL(a.QTD,0)) || ' operações'
FROM agregado a WHERE a.SISTEMA_ORIGEM = 'Oracle'
UNION ALL
SELECT 4, 'HL7/FHIR',
       CASE WHEN NVL(a.ERROS,0) > 10 THEN 'CRITICO'
            WHEN NVL(a.ERROS,0) > 3  THEN 'DEGRADADO'
            ELSE 'OPERACIONAL' END,
       'Barramento · backlog e latência ' || TO_CHAR(NVL(a.LAT_MEDIA,0)) || ' ms',
       'latência ' || TO_CHAR(NVL(a.LAT_MEDIA,0)) || ' ms',
       TO_CHAR(NVL(a.ERROS,0)) || ' em erro/2h',
       TO_CHAR(NVL(a.QTD,0)) || ' mensagens'
FROM agregado a WHERE a.SISTEMA_ORIGEM = 'HL7/FHIR';


/* ------------------------------------------------------------
   6) MV_INTEGRACAO_SERIE_HORA — série de 12 horas
   ------------------------------------------------------------ */
CREATE MATERIALIZED VIEW MV_INTEGRACAO_SERIE_HORA
BUILD IMMEDIATE
REFRESH COMPLETE ON DEMAND
AS
SELECT TRUNC(HORARIO, 'HH24') AS HORA,
       SUM(CASE WHEN TIPO_MENSAGEM LIKE 'ADT%'
                  OR TIPO_MENSAGEM LIKE 'ORM%'
                  OR TIPO_MENSAGEM LIKE 'ORU%'
                  OR TIPO_MENSAGEM LIKE 'SIU%'
                  OR TIPO_MENSAGEM LIKE 'FHIR%'
                THEN 1 ELSE 0 END) AS HL7_PROCESSADAS,
       ROUND(AVG(LATENCIA_MS)) AS LATENCIA_MEDIA_MS,
       0 AS PACS_ESTUDOS
FROM EVENTO_INTEGRACAO
WHERE HORARIO >= SYSTIMESTAMP - INTERVAL '12' HOUR
GROUP BY TRUNC(HORARIO, 'HH24');


/* ------------------------------------------------------------
   7) Refresh automático — a cada 10 minutos
   COMPLETE ON DEMAND é a escolha segura: as definições têm CTEs,
   LISTAGG e agregações condicionais, o que inviabiliza FAST refresh.
   ------------------------------------------------------------ */
BEGIN
  DBMS_SCHEDULER.CREATE_JOB(
    job_name        => 'JOB_REFRESH_MV_INTEGRACAO',
    job_type        => 'PLSQL_BLOCK',
    job_action      => 'BEGIN
                          DBMS_MVIEW.REFRESH(''MV_INTEGRACAO_KPI'', ''C'');
                          DBMS_MVIEW.REFRESH(''MV_INTEGRACAO_SISTEMA'', ''C'');
                          DBMS_MVIEW.REFRESH(''MV_INTEGRACAO_SERIE_HORA'', ''C'');
                        END;',
    start_date      => SYSTIMESTAMP,
    repeat_interval => 'FREQ=MINUTELY; INTERVAL=10',
    enabled         => TRUE,
    comments        => 'Atualiza as views materializadas do módulo Integrações.'
  );
END;
