/* ------------------------------------------------------------
   8) Carga de demonstração — 400 eventos nas últimas 12 horas
   Remova este bloco em produção.
   ------------------------------------------------------------ */
BEGIN
  FOR i IN 1..400 LOOP
    INSERT INTO EVENTO_INTEGRACAO
      (HORARIO, SISTEMA_ORIGEM, SISTEMA_DESTINO, TIPO_MENSAGEM,
       ID_MENSAGEM, PACIENTE, UNIDADE, STATUS, LATENCIA_MS, DETALHE)
    VALUES (
      SYSTIMESTAMP - NUMTODSINTERVAL(DBMS_RANDOM.VALUE(0, 12), 'HOUR'),
      CASE MOD(i,4) WHEN 0 THEN 'MV Soul' WHEN 1 THEN 'PACS/RIS'
                    WHEN 2 THEN 'Oracle' ELSE 'HL7/FHIR' END,
      CASE MOD(i,2) WHEN 0 THEN 'MV Soul' ELSE 'PACS/RIS' END,
      CASE MOD(i,10) WHEN 0 THEN 'ADT^A01' WHEN 1 THEN 'ADT^A03'
                     WHEN 2 THEN 'ADT^A08' WHEN 3 THEN 'ORM^O01'
                     WHEN 4 THEN 'ORU^R01' WHEN 5 THEN 'SIU^S12'
                     WHEN 6 THEN 'DICOM C-STORE' WHEN 7 THEN 'DICOM C-FIND'
                     WHEN 8 THEN 'FHIR Patient' ELSE 'FHIR Observation' END,
      'MSG-' || TO_CHAR(100000 + i),
      CASE MOD(i,6) WHEN 0 THEN 'M. A. S.' WHEN 1 THEN 'J. P. L.'
                    WHEN 2 THEN 'R. C. F.' WHEN 3 THEN 'A. B. M.'
                    WHEN 4 THEN 'L. F. T.' ELSE 'C. S. R.' END,
      CASE MOD(i,4) WHEN 0 THEN 'CER' WHEN 1 THEN 'Mariska'
                    WHEN 2 THEN 'Paulino' ELSE 'Ambulatório' END,
      CASE WHEN MOD(i,13) = 0 THEN 'ERRO'
           WHEN MOD(i,29) = 0 THEN 'PENDENTE'
           ELSE 'SUCESSO' END,
      CASE WHEN MOD(i,13) = 0 THEN ROUND(DBMS_RANDOM.VALUE(1200,4200))
           ELSE ROUND(DBMS_RANDOM.VALUE(120,1500)) END,
      CASE WHEN MOD(i,13) = 0 THEN 'Timeout na resposta do destino'
           ELSE 'ACK recebido' END
    );
  END LOOP;
  COMMIT;
END;
