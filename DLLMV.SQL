/* ============================================================
   02_integracoes_ddl.sql
   Objetivo: criar as tabelas de suporte do módulo Integrações e as
             views materializadas que alimentam o painel.
   Oracle 12c+  |  Executar como owner do schema.

   Estrutura:
     1) EVENTO_INTEGRACAO      tabela base (particionada por mês)
     2) ALERTA_INTEGRACAO      tabela base
     3) ESTUDO_PACS            tabela base (apoio ao RIS)
     4) MV_INTEGRACAO_KPI      view materializada (5 KPIs)
     5) MV_INTEGRACAO_SISTEMA  view materializada (status por sistema)
     6) MV_INTEGRACAO_SERIE_HORA view materializada (série de 12h)
     7) Job de refresh a cada 10 minutos
     8) Carga de dados de demonstração (opcional)
   ============================================================ */

/* ------------------------------------------------------------
   1) EVENTO_INTEGRACAO
   Grão: uma linha por mensagem trocada entre sistemas.
   Particionada por RANGE mensal em HORARIO — consulta de "últimas
   24h" em tabela sem partição degrada rápido conforme o volume cresce.
   ------------------------------------------------------------ */
CREATE TABLE EVENTO_INTEGRACAO (
  ID                 NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  HORARIO            TIMESTAMP(0)   DEFAULT SYSTIMESTAMP NOT NULL,
  SISTEMA_ORIGEM     VARCHAR2(40)   NOT NULL,
  SISTEMA_DESTINO    VARCHAR2(40)   NOT NULL,
  TIPO_MENSAGEM      VARCHAR2(30)   NOT NULL,
  ID_MENSAGEM        VARCHAR2(64)   NOT NULL,
  PACIENTE           VARCHAR2(40),               -- iniciais mascaradas (LGPD)
  UNIDADE            VARCHAR2(40),
  STATUS             VARCHAR2(12)   NOT NULL,    -- SUCESSO | ERRO | PENDENTE
  LATENCIA_MS        NUMBER(8),
  DETALHE            VARCHAR2(250),
  PAYLOAD            CLOB,
  CONSTRAINT PK_EVENTO_INTEGRACAO PRIMARY KEY (ID, HORARIO),
  CONSTRAINT CK_EVENTO_STATUS CHECK (STATUS IN ('SUCESSO','ERRO','PENDENTE')),
  CONSTRAINT CK_EVENTO_LATENCIA CHECK (LATENCIA_MS IS NULL OR LATENCIA_MS >= 0)
)
PARTITION BY RANGE (HORARIO)
INTERVAL (NUMTOYMINTERVAL(1,'MONTH'))
(
  PARTITION P_INICIAL VALUES LESS THAN (TIMESTAMP '2026-01-01 00:00:00')
);

/* Consulta do modo analítico: filtro por sistema + status, ordenada
   por horário decrescente. Índice composto cobre os três usos. */
CREATE INDEX IX_EVENTO_INT_SIST_STAT
  ON EVENTO_INTEGRACAO (SISTEMA_ORIGEM, STATUS, HORARIO DESC) LOCAL;

CREATE INDEX IX_EVENTO_INT_HORARIO
  ON EVENTO_INTEGRACAO (HORARIO DESC) LOCAL;

/* Busca pelo identificador da mensagem — usada na rota de payload */
CREATE INDEX IX_EVENTO_INT_IDMSG
  ON EVENTO_INTEGRACAO (ID_MENSAGEM) LOCAL;

COMMENT ON COLUMN EVENTO_INTEGRACAO.PACIENTE IS
  'Somente iniciais mascaradas. Nome completo nunca deve ser gravado aqui.';


/* ------------------------------------------------------------
   2) ALERTA_INTEGRACAO
   ------------------------------------------------------------ */
CREATE TABLE ALERTA_INTEGRACAO (
  ID               NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  SEVERIDADE       VARCHAR2(10)  NOT NULL,   -- CRITICO | ATENCAO | INFO
  TITULO           VARCHAR2(200) NOT NULL,
  SISTEMA          VARCHAR2(40),
  HORARIO          TIMESTAMP(0)  DEFAULT SYSTIMESTAMP NOT NULL,
  RECONHECIDO      CHAR(1)       DEFAULT 'N' NOT NULL,
  RECONHECIDO_EM   TIMESTAMP(0),
  RECONHECIDO_POR  VARCHAR2(40),
  CONSTRAINT PK_ALERTA_INTEGRACAO PRIMARY KEY (ID),
  CONSTRAINT CK_ALERTA_SEV CHECK (SEVERIDADE IN ('CRITICO','ATENCAO','INFO')),
  CONSTRAINT CK_ALERTA_REC CHECK (RECONHECIDO IN ('S','N'))
);

/* A listagem do painel filtra por RECONHECIDO='N' e ordena por
   severidade e horário. Índice parcial por função resolve. */
CREATE INDEX IX_ALERTA_INT_PEND
  ON ALERTA_INTEGRACAO (RECONHECIDO, HORARIO DESC);

COMMENT ON COLUMN ALERTA_INTEGRACAO.RECONHECIDO_POR IS
  'Impressão SHA-256 curta do token que reconheceu. Nunca o token.';


/* ------------------------------------------------------------
   3) ESTUDO_PACS — apoio ao bloco de imagem e laudos pendentes
   ------------------------------------------------------------ */
CREATE TABLE ESTUDO_PACS (
  ID                NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  DATA_ESTUDO       DATE          NOT NULL,
  MODALIDADE        VARCHAR2(6)   NOT NULL,   -- CR, CT, MR, US, XA
  ACCESSIO_NUMBER   VARCHAR2(64),
  PACIENTE          VARCHAR2(40),              -- iniciais mascaradas
  UNIDADE           VARCHAR2(40),
  LAUDO_CONCLUIDO   CHAR(1)       DEFAULT 'N' NOT NULL,
  CONSTRAINT PK_ESTUDO_PACS PRIMARY KEY (ID),
  CONSTRAINT CK_PACS_LAUDO CHECK (LAUDO_CONCLUIDO IN ('S','N'))
);

CREATE INDEX IX_PACS_DATA_MOD ON ESTUDO_PACS (DATA_ESTUDO, MODALIDADE);
CREATE INDEX IX_PACS_PEND    ON ESTUDO_PACS (LAUDO_CONCLUIDO, DATA_ESTUDO);


/* ------------------------------------------------------------
   4) MV_INTEGRACAO_KPI
   Colunas consumidas pela API:
     CHAVE, ROTULO, VALOR, UNIDADE, VARIACAO, META, HISTORICO, ORDEM
   HISTORICO é uma string de 12 valores separados por vírgula — a
   sparkline do painel desenha a partir dela.
   ------------------------------------------------------------ */
CREATE MATERIALIZED VIEW MV_INTEGRACAO_KPI
BUILD IMMEDIATE
REFRESH COMPLETE ON DEMAND
AS
WITH janela AS (
  SELECT /*+ MATERIALIZE */
         HORARIO, STATUS, LATENCIA_MS,
         TRUNC(HORARIO, 'HH24') AS HORA
  FROM EVENTO_INTEGRACAO
  WHERE HORARIO >= SYSTIMESTAMP - INTERVAL '1' DAY
),
por_hora AS (
  SELECT HORA,
         ROUND(AVG(LATENCIA_MS)) AS LAT_MEDIA,
         ROUND(100 * SUM(CASE WHEN STATUS = 'ERRO' THEN 1 ELSE 0 END)
                     / NULLIF(COUNT(*), 0), 2) AS PCT_ERRO
  FROM janela
  GROUP BY HORA
),
total AS (
  SELECT COUNT(*) AS QTD,
         ROUND(100 * SUM(CASE WHEN STATUS = 'ERRO' THEN 1 ELSE 0 END)
                     / NULLIF(COUNT(*), 0), 2) AS PCT_ERRO_GERAL,
         ROUND(AVG(LATENCIA_MS)) AS LAT_GERAL
  FROM janela
),
pacs_hoje AS (
  SELECT COUNT(*) AS QTD FROM ESTUDO_PACS WHERE DATA_ESTUDO >= TRUNC(SYSDATE)
),
laudos_pend AS (
  SELECT COUNT(*) AS QTD FROM ESTUDO_PACS WHERE LAUDO_CONCLUIDO = 'N'
)
SELECT 1 AS ORDEM,
       'disp'          AS CHAVE,
       'Disponibilidade MV Soul' AS ROTULO,
       TO_CHAR(ROUND(100 - NVL(t.PCT_ERRO_GERAL,0), 1), 'FM9990.0') AS VALOR,
       '%'             AS UNIDADE,
       0               AS VARIACAO,
       '99,5%'         AS META,
       (SELECT LISTAGG(TO_CHAR(ROUND(100 - NVL(PCT_ERRO,0),1),'FM9990.0'), ',')
                 WITHIN GROUP (ORDER BY HORA)
        FROM por_hora) AS HISTORICO
FROM total t
UNION ALL
SELECT 2, 'lat', 'Tempo médio de resposta',
       TO_CHAR(NVL(t.LAT_GERAL,0)),
       'ms', 0, '1.000 ms',
       (SELECT LISTAGG(TO_CHAR(LAT_MEDIA), ',') WITHIN GROUP (ORDER BY HORA) FROM por_hora)
FROM total t
UNION ALL
SELECT 3, 'pacs', 'Estudos PACS hoje',
       TO_CHAR(p.QTD), '', 0, '', NULL
FROM pacs_hoje p
UNION ALL
SELECT 4, 'lau', 'Laudos pendentes no RIS',
       TO_CHAR(l.QTD), '', 0, '< 30', NULL
FROM laudos_pend l
UNION ALL
SELECT 5, 'err', 'Taxa de erro nas integrações',
       TO_CHAR(NVL(t.PCT_ERRO_GERAL,0), 'FM9990.0'),
       '%', 0, '< 1,0%',
       (SELECT LISTAGG(TO_CHAR(NVL(PCT_ERRO,0),'FM9990.0'), ',')
               WITHIN GROUP (ORDER BY HORA)
        FROM por_hora)
FROM total t;


